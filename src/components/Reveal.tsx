import styles from './Reveal.module.css'

type Props = {
  children: React.ReactNode
  /** Направление входа. `up` — сдвиг снизу, `scale` — лёгкий зум. */
  from?: 'up' | 'scale'
  className?: string
}

/**
 * Появление секции при входе в область видимости.
 *
 * Серверный компонент: ни строчки клиентского JS. Вся механика в
 * Reveal.module.css на scroll-driven анимации — там же расписано, почему
 * так, а не через IntersectionObserver, как было раньше.
 *
 * Что изменилось по сравнению с предыдущей версией:
 *  • компонент перестал быть клиентским. Он стоит на восьми страницах, и
 *    каждый экземпляр раньше поднимал свой IntersectionObserver и держал
 *    состояние React — теперь ни того, ни другого;
 *  • контент виден без JS. Прежняя версия скрывала его через opacity: 0 в
 *    CSS, и вернуть видимость мог только скрипт;
 *  • пропало постоянное will-change: opacity, transform. Композитор и так
 *    получает слой от scroll-driven анимации, а висящий will-change на
 *    десятках блоков держит их в отдельных слоях всё время жизни страницы;
 *  • пропал проп delay. Каскад больше не нужен: у каждого блока свой
 *    таймлайн, и разница во времени появления берётся из того, что блоки
 *    физически входят в кадр по очереди. Ровно то же ощущение, без
 *    задержек, которые приходилось выставлять руками;
 *  • направления left / right удалены — в проекте их никто не использовал.
 */
export default function Reveal({ children, from = 'up', className }: Props) {
  return (
    <div
      className={[styles.reveal, styles[from], className]
        .filter(Boolean)
        .join(' ')}
    >
      {children}
    </div>
  )
}
